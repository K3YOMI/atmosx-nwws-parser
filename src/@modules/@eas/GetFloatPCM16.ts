export const GetFloatPCM16 = (float32: Float32Array): Int16Array => {
    const out = new Int16Array(float32.length);
    for (let i = 0; i < float32.length; i++) {
        let v = Math.max(-1, Math.min(1, float32[i]));
        out[i] = Math.round(v * 32767);
    }
    return out;
}

