export const getMergedPCM16 = (arrays: Int16Array[]): Int16Array => {
    let total = 0;
    for (const a of arrays) total += a.length;
    const out = new Int16Array(total);
    let o = 0;
    for (const a of arrays) {
        out.set(a, o);
        o += a.length;
    }
    return out;
}

